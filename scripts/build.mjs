/**
 * Builds InternIQ:
 *   dist/web/                         static site for GitHub Pages (or any static host)
 *   supabase/functions/api/index.ts   the server, bundled for Supabase Edge Functions
 *
 * Usage:
 *   node scripts/build.mjs            production build (reads deploy/public.json and private/)
 *   node scripts/build.mjs --dev      unminified client wired to the local dev server
 *   node scripts/build.mjs --public   ignore private/ (what CI and tests use)
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

async function readJson(path) {
  try {
    return JSON.parse(await readFile(path, 'utf8'));
  } catch {
    return null;
  }
}

/**
 * The deployer's private seed (git-ignored private/ folder): profile, roadmap
 * tasks and programme ratings. Compiled into the server only; the server applies
 * it to the account whose email is INTERNIQ_OWNER_EMAIL and to nobody else.
 */
export async function loadPersonalSeed({ usePrivate = !process.argv.includes('--public') } = {}) {
  if (!usePrivate) return null;
  const seed = await readJson(join(root, 'private/seed.json'));
  const ratings = await readJson(join(root, 'private/ratings.json'));
  return seed || ratings ? { version: 1, ...(seed ?? {}), ratings: ratings ?? undefined } : null;
}

/** Public settings for the web build (safe to commit). */
export async function loadPublicConfig() {
  const cfg = (await readJson(join(root, 'deploy/public.json'))) ?? {};
  const supabaseUrl = String(cfg.supabaseUrl ?? '').replace(/\/+$/, '');
  return {
    supabaseUrl,
    anonKey: String(cfg.anonKey ?? ''),
    appUrl: String(cfg.appUrl ?? ''),
    operator: String(cfg.operator ?? ''),
    contact: String(cfg.contact ?? ''),
  };
}

/** @param {{ personal?: object | null }} [opts] */
export async function buildServer(opts = {}) {
  const personal = opts.personal === undefined ? await loadPersonalSeed() : opts.personal;
  const result = await build({
    entryPoints: [join(root, 'src/server/edge/deno.ts')],
    bundle: true,
    format: 'esm',
    target: 'es2022',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    charset: 'utf8',
    legalComments: 'none',
    external: ['node:*'],
    write: false,
    logLevel: 'warning',
    define: { __IIP_PERSONAL__: JSON.stringify(personal) },
  });
  const header = `// @ts-nocheck\n// InternIQ v${pkg.version}: generated by scripts/build.mjs from src/server. Edit src/, not this file.\n`;
  return { code: header + result.outputFiles[0].text, personal: Boolean(personal) };
}

function hashOf(text) {
  return createHash('sha256').update(text).digest('hex').slice(0, 10);
}

function csp(supabaseUrl, dev) {
  const connect = dev ? "'self'" : `'self' ${supabaseUrl}`.trim();
  return [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
    "font-src 'self' https://fonts.gstatic.com",
    "img-src 'self' data: https://*.googleusercontent.com",
    `connect-src ${connect}`,
    "base-uri 'self'",
    "form-action 'self'",
    "object-src 'none'",
  ].join('; ');
}

/**
 * @param {{ dev?: boolean; config?: { supabaseUrl: string; anonKey: string; appUrl: string; operator: string; contact: string } }} [opts]
 */
export async function buildClient(opts = {}) {
  const { dev = false, config } = opts;
  const cfg = config ?? (await loadPublicConfig());
  const clientConfig = dev
    ? { mode: 'dev', supabaseUrl: '', anonKey: '', apiUrl: '/api', appUrl: '', operator: 'your dev server' }
    : { mode: 'hosted', supabaseUrl: cfg.supabaseUrl, anonKey: cfg.anonKey, apiUrl: cfg.supabaseUrl ? `${cfg.supabaseUrl}/functions/v1/api` : '', appUrl: cfg.appUrl, operator: cfg.operator };
  const result = await build({
    entryPoints: [join(root, 'src/client/main.tsx')],
    bundle: true,
    format: 'esm',
    target: 'es2020',
    platform: 'browser',
    jsx: 'automatic',
    jsxImportSource: 'preact',
    minify: !dev,
    sourcemap: dev ? 'inline' : false,
    define: {
      'process.env.NODE_ENV': dev ? '"development"' : '"production"',
      __APP_VERSION__: JSON.stringify(pkg.version),
      __IIP_CONFIG__: JSON.stringify(clientConfig),
    },
    outdir: 'out',
    write: false,
    legalComments: 'none',
    logLevel: 'warning',
    loader: { '.svg': 'text' },
  });
  const js = result.outputFiles.find((f) => f.path.endsWith('.js'))?.text ?? '';
  const css = result.outputFiles.find((f) => f.path.endsWith('.css'))?.text ?? '';
  const boot = await readFile(join(root, 'src/client/boot.js'), 'utf8');
  const files = {
    [`app-${hashOf(js)}.js`]: js,
    [`app-${hashOf(css)}.css`]: css,
    [`boot-${hashOf(boot)}.js`]: boot,
  };
  const names = Object.keys(files);
  const template = await readFile(join(root, 'src/client/index.html'), 'utf8');
  const html = template
    .replace('%CSP%', () => csp(cfg.supabaseUrl, dev))
    .replace('%APP_URL%', () => cfg.appUrl)
    .replace('%APP_CSS%', () => names[1])
    .replace('%APP_JS%', () => names[0])
    .replace('%BOOT_JS%', () => names[2]);
  return { html, files, jsBytes: js.length, cssBytes: css.length, config: clientConfig, publicConfig: cfg };
}

/** Static pages (privacy, terms, favicon) with the operator's details filled in. */
async function publicFiles(cfg) {
  const dir = join(root, 'src/client/public');
  const out = {};
  const updated = new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
  const contact = cfg.contact
    ? /@/.test(cfg.contact) && !/^https?:/.test(cfg.contact)
      ? `email <a href="mailto:${cfg.contact}">${cfg.contact}</a>`
      : `<a href="${cfg.contact}">${cfg.contact}</a>`
    : 'open an issue at <a href="https://github.com/DhruvBasia/internship-intelligence-platform/issues">github.com/DhruvBasia/internship-intelligence-platform</a>';
  for (const name of await readdir(dir)) {
    let text = await readFile(join(dir, name), 'utf8');
    if (name.endsWith('.html')) {
      text = text
        .replaceAll('%OPERATOR%', cfg.operator || 'the person who shared it with you')
        .replaceAll('%APP_URL%', cfg.appUrl || './')
        .replaceAll('%CONTACT%', contact)
        .replaceAll('%UPDATED%', updated);
    }
    out[name] = text;
  }
  return out;
}

async function main() {
  const dev = process.argv.includes('--dev');
  const web = join(root, 'dist/web');
  await rm(web, { recursive: true, force: true });
  await mkdir(web, { recursive: true });
  const [server, client] = await Promise.all([buildServer(), buildClient({ dev })]);
  await writeFile(join(web, 'index.html'), client.html);
  for (const [name, text] of Object.entries(client.files)) await writeFile(join(web, name), text);
  for (const [name, text] of Object.entries(await publicFiles(client.publicConfig))) await writeFile(join(web, name), text);
  // GitHub Pages serves 404.html for unknown paths; the app routes with #hash, so send them home.
  await copyFile(join(web, 'index.html'), join(web, '404.html'));
  const fnDir = join(root, 'supabase/functions/api');
  await mkdir(fnDir, { recursive: true });
  await writeFile(join(fnDir, 'index.ts'), server.code);
  const kb = (n) => (n / 1024).toFixed(1) + ' KB';
  const c = client.config;
  console.log(`web     ${dev ? 'dev' : c.supabaseUrl ? `hosted → ${c.supabaseUrl}` : 'hosted (NOT CONFIGURED: fill deploy/public.json)'}  js ${kb(client.jsBytes)}  css ${kb(client.cssBytes)}`);
  console.log(`server  ${kb(server.code.length)}  ${server.personal ? '(includes your private seed for the owner account)' : '(no private seed)'}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
