/**
 * Build for Apps Script:
 *   dist/Code.js        server bundle + one top-level stub per exported function
 *   dist/index.html     client UI with JS and CSS inlined (HtmlService serves one file)
 *   dist/appsscript.json
 *
 * Usage: node scripts/build.mjs [--dev]   (--dev keeps the client unminified)
 */
import { build } from 'esbuild';
import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const dev = process.argv.includes('--dev');
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

export async function buildServer() {
  const result = await build({
    entryPoints: [join(root, 'src/server/main.ts')],
    bundle: true,
    format: 'iife',
    globalName: '__IIP',
    target: 'es2020',
    platform: 'neutral',
    charset: 'utf8',
    legalComments: 'none',
    write: false,
    logLevel: 'warning',
  });
  const code = result.outputFiles[0].text;
  // Evaluate the bundle once (with no Apps Script globals) to discover its exports.
  const ctx = { console };
  vm.createContext(ctx);
  vm.runInContext(code + '\n;globalThis.__exports = Object.keys(__IIP);', ctx);
  const names = ctx.__exports;
  if (!names.includes('doGet')) throw new Error('Server bundle must export doGet');
  const stubs = names
    .map((n) => `function ${n}() { return __IIP.${n}.apply(this, arguments); }`)
    .join('\n');
  const header = `// InternIQ v${pkg.version}: generated by scripts/build.mjs. Edit src/, not this file.\n`;
  return { code: header + code + '\n\n' + stubs + '\n', names };
}

export async function buildClient() {
  const result = await build({
    entryPoints: [join(root, 'src/client/main.tsx')],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    platform: 'browser',
    jsx: 'automatic',
    jsxImportSource: 'preact',
    minify: !dev,
    sourcemap: dev ? 'inline' : false,
    define: { 'process.env.NODE_ENV': dev ? '"development"' : '"production"', __APP_VERSION__: JSON.stringify(pkg.version) },
    outdir: 'out',
    write: false,
    legalComments: 'none',
    logLevel: 'warning',
    loader: { '.svg': 'text' },
  });
  const js = result.outputFiles.find((f) => f.path.endsWith('.js'))?.text ?? '';
  const css = result.outputFiles.find((f) => f.path.endsWith('.css'))?.text ?? '';
  const template = await readFile(join(root, 'src/client/index.html'), 'utf8');
  // A literal "</script" inside the bundle would end the inline script early.
  const safeJs = js.replace(/<\/script/gi, '<\\/script');
  const html = template
    .replace('/*__IIP_CSS__*/', () => css)
    .replace('/*__IIP_JS__*/', () => safeJs);
  return { html, jsBytes: js.length, cssBytes: css.length };
}

async function main() {
  await mkdir(dist, { recursive: true });
  const [server, client] = await Promise.all([buildServer(), buildClient()]);
  await writeFile(join(dist, 'Code.js'), server.code);
  await writeFile(join(dist, 'index.html'), client.html);
  await copyFile(join(root, 'appsscript.json'), join(dist, 'appsscript.json'));
  const kb = (n) => (n / 1024).toFixed(1) + ' KB';
  console.log(`server  ${kb(server.code.length)}  (${server.names.length} functions)`);
  console.log(`client  js ${kb(client.jsBytes)}  css ${kb(client.cssBytes)}  html ${kb(client.html.length)}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
